static void draw_rect(uint8_t *fb, int x, int y, int w, int h, uint8_t color) {
    for (int yy = y; yy < y + h; yy++) {
        for (int xx = x; xx < x + w; xx++) {
            if (xx >= 0 && xx < FRAMEBUFFER_WIDTH && yy >= 0 && yy < FRAMEBUFFER_HEIGHT)
                fb[yy * FRAMEBUFFER_WIDTH + xx] = color;
        }
    }
}

static void draw_char(uint8_t *fb, int x, int y, char c, uint8_t color) {
    if (c > 127) return;
    for (int i = 0; i < 8; i++) {
        uint8_t line = font8x8_basic[(int)c][i];
        for (int j = 0; j < 8; j++) {
            if ((line >> (7 - j)) & 1) { 
                int px = x + j;
                int py = y + i;
                if (px >= 0 && px < FRAMEBUFFER_WIDTH && py >= 0 && py < FRAMEBUFFER_HEIGHT)
                    fb[py * FRAMEBUFFER_WIDTH + px] = color;
            }
        }
    }
}

static void draw_string(uint8_t *fb, int x, int y, const char *s, uint8_t color) {
    while (*s) {
        draw_char(fb, x, y, *s++, color);
        x += 8;
    }
}

// --- Overlay helpers ---

static void draw_frame(uint8_t *fb, int x, int y, int w, int h, uint8_t bg, uint8_t border) {
    draw_rect(fb, x, y, w, h, border);
    draw_rect(fb, x + 1, y + 1, w - 2, h - 2, bg);
}

static int str_len(const char *s) {
    int n = 0;
    while (s[n]) n++;
    return n;
}

static void draw_toast(uint8_t *fb, const char *text) {
    int w = str_len(text) * 8 + 10;
    int x = (FRAMEBUFFER_WIDTH - w) / 2;
    draw_frame(fb, x, TOAST_Y, w, 14, COLOR_BG, COLOR_FG);
    draw_string(fb, x + 5, TOAST_Y + 3, text, COLOR_FG);
}

static void draw_brightness_bar(uint8_t *fb) {
    const int seg_w = 8, seg_h = 6, gap = 2;
    const int bar_w = BRIGHTNESS_LEVELS * (seg_w + gap) - gap;
    const int box_w = bar_w + 10;
    const int box_x = (FRAMEBUFFER_WIDTH - box_w) / 2;
    uint8_t level = brightness_get_level();

    draw_frame(fb, box_x, BAR_Y, box_w, seg_h + 10, COLOR_BG, COLOR_FG);
    for (int i = 0; i < BRIGHTNESS_LEVELS; i++) {
        int sx = box_x + 5 + i * (seg_w + gap);
        if (i <= level)
            draw_rect(fb, sx, BAR_Y + 5, seg_w, seg_h, COLOR_FG);
        else
            draw_frame(fb, sx, BAR_Y + 5, seg_w, seg_h, COLOR_BG, COLOR_FG);
    }
}

static void draw_palette_menu(uint8_t *fb) {
    int count = palette_count();
    char counter[8];
    int n = 0;

    // "3/17" style position counter
    int pos = selection + 1;
    if (pos >= 10) counter[n++] = '0' + pos / 10;
    counter[n++] = '0' + pos % 10;
    counter[n++] = '/';
    if (count >= 10) counter[n++] = '0' + count / 10;
    counter[n++] = '0' + count % 10;
    counter[n] = 0;

    draw_frame(fb, MENU_X, MENU_Y, MENU_W, MENU_BOX_H, COLOR_BG, COLOR_FG);
    draw_string(fb, MENU_X + 6, MENU_Y + 4, "PALETTE", COLOR_FG);
    draw_string(fb, MENU_X + MENU_W - 6 - n * 8, MENU_Y + 4, counter, COLOR_FG);
    draw_rect(fb, MENU_X + 3, MENU_Y + 15, MENU_W - 6, 1, COLOR_FG);

    int first = (selection >= MAX_VISIBLE) ? selection - MAX_VISIBLE + 1 : 0;

    for (int i = 0; i < MAX_VISIBLE && (first + i) < count; i++) {
        int idx = first + i;
        int y_pos = ITEMS_Y + (i * ROW_H);

        if (idx == selection) {
            draw_rect(fb, MENU_X + 3, y_pos - 2, MENU_W - 18, 11, COLOR_HL);
            draw_string(fb, MENU_X + 6, y_pos, palette_name(idx), COLOR_BG);
        } else {
            draw_string(fb, MENU_X + 6, y_pos, palette_name(idx), COLOR_FG);
        }
    }

    // Scroll arrows when more items are hidden above / below
    if (first > 0)
        draw_char(fb, MENU_X + MENU_W - 12, ITEMS_Y, '^', COLOR_FG);
    if (first + MAX_VISIBLE < count)
        draw_char(fb, MENU_X + MENU_W - 12, ITEMS_Y + (MAX_VISIBLE - 1) * ROW_H, 'v', COLOR_FG);
}

// --- Menu behaviour ---

static void close_menu_and_revert(void) {
    // Cancel: go back to the palette that was active before opening the menu
    palette_apply(menu_original_palette);
    selection = menu_original_palette;
    visible = false;
}

void menu_init(void) {
    gpio_init(PIN_UP);
    gpio_set_dir(PIN_UP, GPIO_IN);
    gpio_pull_up(PIN_UP);

    gpio_init(PIN_DOWN);
    gpio_set_dir(PIN_DOWN, GPIO_IN);
    gpio_pull_up(PIN_DOWN);

    gpio_init(PIN_CENTER);
    gpio_set_dir(PIN_CENTER, GPIO_IN);
    gpio_pull_up(PIN_CENTER);

    visible = false;
    selection = settings_get_palette();
    menu_original_palette = selection;
}

bool menu_is_visible(void) {
    return visible;
}

void menu_update(void) {
    uint32_t now = to_ms_since_boot(get_absolute_time());
    bool c_up = !gpio_get(PIN_UP);
    bool c_down = !gpio_get(PIN_DOWN);
    bool c_center = !gpio_get(PIN_CENTER);

    // ---- Center button ----
    if (c_center && !last_center) {
        center_press_start = now;
    } else if (!c_center && last_center) {
        uint32_t duration = now - center_press_start;

        if (duration > LONG_PRESS_MS) {
            // LONG PRESS: open the menu, or cancel it if already open
            if (!visible) {
                menu_original_palette = palette_current();
                selection = menu_original_palette;
                visible = true;
                last_action = now;
            } else {
                close_menu_and_revert();
            }
        } else if (visible) {
            // SHORT PRESS inside the menu: confirm the previewed palette
            palette_apply_no_save(selection);
            visible = false;
            save_due_at = now;              // save right away
            save_pending = true;
        }
    }
    last_center = c_center;

    // ---- Up / Down ----
    if (!visible) {
        // Outside the menu UP/DOWN change the backlight brightness
        static uint32_t last_btn_time = 0;
        if (now - last_btn_time > 150) {
            if (c_up || c_down) {
                if (c_up) brightness_up();
                if (c_down) brightness_down();
                last_btn_time = now;
                bar_until = now + BAR_SHOW_MS;
                save_due_at = now + BRIGHTNESS_SAVE_DELAY;   // save once the user stops pressing
                save_pending = true;
            }
        }
    } else {
        // Inside the menu UP/DOWN scroll the list with live preview
        if (c_up && (now - last_action >= SCROLL_DELAY)) {
            if (selection > 0) {
                selection--;
                palette_apply(selection);
            }
            last_action = now;
        }
        if (c_down && (now - last_action >= SCROLL_DELAY)) {
            if (selection < palette_count() - 1) {
                selection++;
                palette_apply(selection);
            }
            last_action = now;
        }
        // Auto-close (and cancel) on timeout
        if (now - last_action > MENU_TIMEOUT) close_menu_and_revert();
    }

    // ---- Automatic save ----
    if (save_pending && !visible && (int32_t)(now - save_due_at) >= 0) {
        save_pending = false;
        if (settings_save_if_changed()) {
            toast_until = to_ms_since_boot(get_absolute_time()) + TOAST_SHOW_MS;
        }
    }
}

void menu_draw_overlay(uint8_t buffer_index) {
    uint32_t now = to_ms_since_boot(get_absolute_time());
    uint8_t *fb = get_framebuffer(buffer_index);

    if (visible) {
        draw_palette_menu(fb);
    } else if ((int32_t)(bar_until - now) > 0) {
        draw_brightness_bar(fb);
    }

    if ((int32_t)(toast_until - now) > 0) {
        draw_toast(fb, "SAVED");
    }
}
